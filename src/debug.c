/* ============================ tile data viewer ============================ */

static void draw_tile_row(u8 byte1, uint8_t byte2, u32 buf[], u32 palette[])
{
        for (int bit = 7, i = 0; bit >= 0; bit--) {
                int px = ((byte1 >> bit) & 1) | (u8)(((byte2 >> bit) & 1) << 1);
                buf[i++] = palette[px];
        }
}

static void draw_tile_data(struct ppu *ppu, u32 buf[])
{
        u32 border_colour = ppu->palette[3];

        for (int y = 0; y < 24; y++) {
                for (int row = 0; row < 8; row++) {
                        u8 *p = ppu->vram + 16 * y * 16 + row * 2;
                        for (int x = 0; x < 16; x++, p += 16) {
                                draw_tile_row(p[0], p[1], buf, ppu->palette);
                                buf += 8;
                                if (x != 15)
                                        *buf++ = border_colour;
                        }
                }
                if (y != 23)
                        for (int i = 0; i < 16 * 8 + 15; i++)
                                *buf++ = border_colour;
        }
}

/* ========================= background map viewer ========================== */

static void draw_tile(uint8_t *tile, u32 buf[], int i, int bufw, u32 palette[])
{
        int  y = i / (bufw / 8);
        int  x = i % (bufw / 8);
        u32 *p = buf + 8 * (y * bufw + x);

        for (int row = 0; row < 8; row++, p += bufw)
                draw_tile_row(tile[row * 2], tile[row * 2 + 1], p, palette);
}

static void draw_horizontal_line(int x, int y, int len, u32 buf[], u32 colour)
{
        u32 *line = buf + y * 256;

        if (x + len < 256) {
                for (int i = 0; i < len; i++)
                        line[x + i] = colour;
        } else {
                for (int i = x; i < 256; i++, len--)
                        line[i] = colour;
                for (int i = 0; i < len; i++)
                        line[i] = colour;
        }
}

static void draw_vertical_line(int x, int y, int len, u32 buf[], u32 colour)
{
        u32 *p = buf + x;

        if (y + len < 256) {
                for (int i = 0; i < len; i++)
                        p[(y + i) * 256] = colour;
        } else {
                for (int i = y; i < 256; i++, len--)
                        p[i * 256] = colour;
                for (int i = 0; i < len; i++)
                        p[i * 256] = colour;
        }
}

static void draw_viewport_border(struct ppu *ppu, u32 buf[], u32 colour)
{
        u8 left   = ppu->scx;
        u8 top    = ppu->scy;
        u8 right  = left + 159;
        u8 bottom = top + 143;

        draw_horizontal_line(left, top, 160, buf, colour);
        draw_horizontal_line(left, bottom, 160, buf, colour);

        draw_vertical_line(left, top, 144, buf, colour);
        draw_vertical_line(right, top, 144, buf, colour);
}

static u8 * get_tile(struct ppu *ppu, u8 i)
{
        u8   *tile_addr     = ppu->vram + i * 16;
        bool  signed_method = (ppu->lcdc >> 4) & 0x1;
        signed_method = false;

        return signed_method ? tile_addr + 0x1000 : tile_addr;
}

static void draw_tilemap_0x9800(struct ppu *ppu, u32 buf[])
{
        u8 *tile = ppu->vram + 0x1800;

        for (int i = 0; i < 32 * 32; i++)
                draw_tile(get_tile(ppu, *tile++), buf, i, 256, ppu->palette);

        draw_viewport_border(ppu, buf, ppu->palette[3]);
}

static void draw_tilemap_0x9C00(struct ppu *ppu, u32 buf[])
{
        u8 *tile = ppu->vram + 0x1C00;

        for (int i = 0; i < 32 * 32; i++)
                draw_tile(get_tile(ppu, *tile++), buf, i, 256, ppu->palette);

        draw_viewport_border(ppu, buf, ppu->palette[3]);
}

/* ============================= sprites viewer ============================= */

static void draw_sprites(struct ppu *ppu, u32 buf[], u32 palette[])
{
        u8 *p = ppu->oam + 2;
        for (int i = 0; i < 40; i++, p += 4)
                draw_tile(get_tile(ppu, *p), buf, i, 8 * 10, palette);
}

