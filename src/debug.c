static void draw_info_string_(char *s, int row, u32 *buf, int bufw, u32 *palette)
{
        for (int x = 0; s[x] != '\0'; x++) {
                u8 *tile = tile_char(s[x]);
                draw_tile(tile, buf, row * (bufw / 8) + x, bufw, palette);
        }
}

